const LON0 = 172.5;
const LAT0 = -41;
const COS = Math.cos((41 * Math.PI) / 180);

/** Project lon/lat onto a flat plane in map units (x east, y south). */
export function project(lon: number, lat: number): [number, number] {
  return [(lon - LON0) * COS, -(lat - LAT0)];
}

export const OUTLINES = [NORTH_ISLAND, SOUTH_ISLAND, STEWART_ISLAND].map((poly) => poly.map(([lon, lat]) => project(lon, lat)));
